количество = int(input())

первое = int(input())
общая_сумма = первое
кол_положительных = 1 if первое > 0 else 0
максимум = первое

for _ in range(количество - 1):
  число = int(input())
  общая_сумма += число
  if число > 0:
    кол_положительных += 1
  if число > максимум:
    максимум = число

print('Сумма:', общая_сумма)
print('Количество положительных:', кол_положительных)
print('Максимум:', максимум)
