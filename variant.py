количество_чисел = int(input('Введите кол-во чисел: '))

счётчик = 0
общая_сумма = 0

for _ in range(количество_чисел):
  число = int(input('Введите число: '))
  if число % 3 == 0:
    счётчик += 1
    общая_сумма += число

print('=' * 40)
print('Количество:', счётчик)
print('Сумма:', общая_сумма)
print('=' * 40)
