первое_число = int(input('Введите первое число: '))
второе_число = int(input('Введите второе число: '))


if первое_число < второе_число:
    for i in range(первое_число, второе_число + 1, 1):
        print(i)
elif первое_число > второе_число:
    for i in range(первое_число, второе_число - 1, -1):
            print(i)
else:
     print(первое_число)
